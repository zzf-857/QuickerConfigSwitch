/** pickLang chooses "zh" for any Chinese locale, "en" otherwise. */
export function pickLang(langs) {
  for (const l of langs || []) {
    if (/^zh\b/i.test(l)) return 'zh';
    if (/^en\b/i.test(l)) return 'en';
  }
  return (langs && langs.length) ? 'en' : 'zh';
}

const navLangs = typeof navigator !== 'undefined'
  ? (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language])
  : [];

export let lang = pickLang(navLangs);

export function setLang(l) { lang = l; }

/** t looks a key up in the current language (falling back to zh) and fills {vars}. */
export function t(key, vars) {
  let s = strings[lang]?.[key] ?? strings.zh[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}
